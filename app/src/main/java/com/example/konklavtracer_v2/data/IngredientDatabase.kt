    fun getIngredientsByCategory(category: IngredientCategory): List<Ingredient> {
        return allIngredients.filter { it.category == category }
    }

    fun getIngredientById(id: String): Ingredient? {
        return allIngredients.find { it.id == id }
    }

    fun searchIngredients(query: String): List<Ingredient> {
        return allIngredients.filter {
            it.name.contains(query, ignoreCase = true) ||
                    it.description.contains(query, ignoreCase = true) ||
                    it.properties.contains(query, ignoreCase = true)
        }
    }
